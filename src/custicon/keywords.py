def english_fragments(query: str, table: dict[str, tuple[str, ...]] | None = None) -> list[str]:
    needle = normalize_text(query.strip())
    if len(needle) < MINIMUM_LENGTH:
        return []
    fragments = []
    for word, names in (KEYWORDS if table is None else table).items():
        if word.startswith(needle):
            fragments.extend(name for name in names if name not in fragments)
    return fragments
